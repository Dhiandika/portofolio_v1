export const getTechIcon = (tech: string): string => {
    // 1. Direct match
    if (techIcons[tech]) return techIcons[tech];

    // 2. Case-insensitive exact match
    const lowerTech = tech.toLowerCase().trim();
    const exactKey = Object.keys(techIcons).find(k => k.toLowerCase() === lowerTech);
    if (exactKey) return techIcons[exactKey];

    // 3. Partial match — check if the tech string starts with or contains a known key
    const partialKey = Object.keys(techIcons).find(k =>
        lowerTech.startsWith(k.toLowerCase()) ||
        k.toLowerCase().startsWith(lowerTech) ||
        lowerTech.includes(k.toLowerCase())
    );
    if (partialKey) return techIcons[partialKey];

    // 4. No icon found — return empty string (trigger CSS fallback badge)
    return '';
};

/**
 * Returns a consistent neo-brutalist color pair for any tech string.
 * Uses a simple hash so the same tech always gets the same color.
 */
export const getTechColor = (tech: string): { bg: string; text: string } => {
    const palette = [
        { bg: '#FBFF48', text: '#000000' }, // neo-yellow
        { bg: '#3BFF7E', text: '#000000' }, // neo-green
        { bg: '#3B82F6', text: '#ffffff' }, // blue
        { bg: '#FF2D78', text: '#ffffff' }, // neo-pink
        { bg: '#F97316', text: '#ffffff' }, // orange
        { bg: '#A855F7', text: '#ffffff' }, // purple
        { bg: '#00E5FF', text: '#000000' }, // cyan
        { bg: '#111111', text: '#FBFF48' }, // black + yellow text
        { bg: '#e11d48', text: '#ffffff' }, // red
        { bg: '#0ea5e9', text: '#ffffff' }, // sky blue
    ];
    let hash = 0;
    for (let i = 0; i < tech.length; i++) {
        hash = tech.charCodeAt(i) + ((hash << 5) - hash);
    }
    return palette[Math.abs(hash) % palette.length];
};

/**
 * Returns a 2-3 char uppercase abbreviation for a tech name.
 * e.g. "Redis - Websockets" → "RW", "Next.js" → "NX", "TypeScript" → "TS"
 */
export const getTechAbbrev = (tech: string): string => {
    const words = tech.split(/[\s\-_\.\/]+/).filter(Boolean);
    if (words.length === 1) {
        // Single word: first 2 chars, or first + last consonant
        return tech.slice(0, 2).toUpperCase();
    }
    // Multi-word: first letter of each word, max 3
    return words.map(w => w[0]).join('').slice(0, 3).toUpperCase();
};


